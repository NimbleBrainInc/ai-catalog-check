// Renders COVERAGE.md: every requirement of each spec version this release
// checks, and whether the suite checks it. `npm run coverage` writes it; a test
// fails when the committed file is out of date.

import { fileURLToPath } from "node:url";
import { loadRegistry, type Requirement, SPEC_VERSIONS } from "./registry.ts";

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function disposition(r: Requirement): string {
  if (r.check) return `checked (${r.check})`;
  if (r.pending) return `pending: ${r.reason}`;
  return `excluded: ${r.excluded}`;
}

export function coverageMarkdown(): string {
  const lines = [
    "# Coverage",
    "",
    "Every requirement of each AI Catalog version this release checks, and whether the suite checks it.",
    "Generated by `npm run coverage` from `requirements/`; do not edit by hand.",
  ];
  for (const version of [...SPEC_VERSIONS].reverse()) lines.push("", ...versionSection(version));
  return `${lines.join("\n")}\n`;
}

function versionSection(version: string): string[] {
  const registry = loadRegistry(version);
  const all = registry.requirements;
  const count = (f: (r: Requirement) => unknown) => all.filter(f).length;
  const roles = [...new Set(all.map((r) => r.role))];
  return [
    `## AI Catalog ${version}`,
    "",
    `Spec: [${registry.spec.title} ${registry.spec.version}](${registry.spec.source}) (${registry.spec.status}), commit \`${registry.spec.commit.slice(0, 12)}\`, from \`requirements/${version}.yaml\`.`,
    "",
    `| | Requirements |`,
    `|---|---|`,
    `| Checked | ${count((r) => r.check)} |`,
    `| Pending | ${count((r) => r.pending)} |`,
    `| Excluded | ${count((r) => r.excluded)} |`,
    `| **Total** | **${all.length}** |`,
    "",
    "By the role each requirement binds:",
    "",
    "| Role | Checked | Pending | Excluded |",
    "|---|---|---|---|",
    ...roles.map(
      (role) =>
        `| ${role} | ${count((r) => r.role === role && r.check)} | ${count((r) => r.role === role && r.pending)} | ${count((r) => r.role === role && r.excluded)} |`,
    ),
    "",
    `### Requirements of ${version}`,
    "",
    "| ID | Name | Strength | Role | Disposition | Statement |",
    "|---|---|---|---|---|---|",
    ...all.map(
      (r) =>
        `| [${r.id}](${registry.spec.published}#${r.section}) | ${cell(r.title ?? "")} | ${r.strength} | ${r.role} | ${cell(disposition(r))} | ${cell(r.text)} |`,
    ),
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.stdout.write(coverageMarkdown());
}
